"""Writes src/pikaseko256_step0.h: the unkeyed state after step 0 (the IV with the zero key,
one step at t = 0), which is the same for every message. Usage:
    python3 tools/gen_step0.py > src/pikaseko256_step0.h"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ref"))
import pikaseko256 as ref  # noqa: E402

r = ref.step(ref.initial_state([0] * 8), 0)
print("// Copyright (c) 2026 Jyrki Alakuijala")
print("// SPDX-License-Identifier: MIT")
print("// Generated by tools/gen_step0.py from the Python reference; do not edit.")
print("// The unkeyed state after step 0: the zero-key IV (SPEC.md, section 4) after one step at")
print("// t = 0. No packet enters before step 0, so every unkeyed hash starts from this state at")
print("// t = 1, with the injection of its first group. Word 8i + l is lane l of register r_i.")
print("#ifndef PIKASEKO256_STEP0_H_")
print("#define PIKASEKO256_STEP0_H_")
print("#include <stdint.h>")
print("static const uint64_t kPikasekoUnkeyedStep0[128] = {")
words = [w for v in r for w in ref.lanes(v)]
for i in range(0, 128, 4):
    print("    " + ", ".join("0x%016xull" % w for w in words[i:i + 4]) + ",")
print("};")
print("#endif  // PIKASEKO256_STEP0_H_")
