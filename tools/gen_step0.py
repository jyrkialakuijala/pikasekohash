"""Writes src/pikaseko256_step0.h: the unkeyed states after step 0 (the IV with the zero key
and the unkeyed domain word, one step at t = 0), one for the 256-bit and one for the 64-bit
digest; they are the same for every message. Usage:
    python3 tools/gen_step0.py > src/pikaseko256_step0.h"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ref"))
import pikaseko256 as ref  # noqa: E402

print("// Copyright (c) 2026 Jyrki Alakuijala")
print("// SPDX-License-Identifier: MIT")
print("// Generated by tools/gen_step0.py from the Python reference; do not edit.")
print("// The unkeyed states after step 0: the zero-key IV with the unkeyed domain word (SPEC.md,")
print("// section 4) after one step at t = 0; [0] for the 256-bit digest, [1] for the 64-bit one.")
print("// No packet enters before step 0, so every unkeyed hash starts from one of them.")
print("// Word 8i + l is lane l of register r_i.")
print("#ifndef PIKASEKO256_STEP0_H_")
print("#define PIKASEKO256_STEP0_H_")
print("#include <stdint.h>")
print("static const uint64_t kPikasekoUnkeyedStep0[2][128] = {")
for out_len in (32, 8):
    r = ref.step(ref.initial_state([0] * 8, ref.domain(0, 0, 0, out_len)), 0)
    words = [w for v in r for w in ref.lanes(v)]
    print("  {")
    for i in range(0, 128, 4):
        print("    " + ", ".join("0x%016xull" % w for w in words[i:i + 4]) + ",")
    print("  },")
print("};")
print("#endif  // PIKASEKO256_STEP0_H_")
